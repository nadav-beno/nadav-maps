// Builds packages/core/src/names/world.ts (correction targets for search typos) from the
// bundled offline world map: city names in English and Hebrew with their population.
// Run: node scripts/gen-names.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const world = JSON.parse(readFileSync(new URL('../apps/web/public/offline/world-1.json', import.meta.url), 'utf8'));
const clean = (s) => String(s ?? '').replace(/[|\n`$\\]/g, ' ').trim();
const lines = [];
for (const [en, he, , , pop] of world.cities) lines.push([clean(he), clean(en), Math.round(pop)].join('|'));
for (const c of world.countries) lines.push([clean(c.he), clean(c.n), 'country'].join('|'));
const out = `// Generated by scripts/gen-names.mjs from apps/web/public/offline/world-1.json
// (Natural Earth, public domain; GeoNames, CC BY 4.0). Do not edit by hand.
/** World cities "hebrew|english|population (thousands)" and countries "hebrew|english|country". */
export const WORLD_NAMES = \`
${lines.join('\n')}
\`;
`;
writeFileSync(new URL('../packages/core/src/names/world.ts', import.meta.url), out);
console.log(`${lines.length} names`);
